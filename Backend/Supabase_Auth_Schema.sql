-- =============================
-- 2. USER PROFILE (Supabase Auth Integration)
-- =============================
-- This table references Supabase Auth users
create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name varchar(100) not null,
  username varchar(100) unique not null,
  email varchar(150) unique not null,
  phone_number varchar(20),
  role varchar(20) default 'User',
  target_level_id integer references levels(level_id),
  is_active boolean default true,
  created_at timestamptz default now(),
  updated_at timestamptz
);

-- =============================
-- 3. TRIGGER FUNCTION - Auto-create profile on user signup
-- =============================
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, username, name)
  values (new.id, new.email, new.email, new.email); -- Use email as default username/name
  return new;
end;
$$ language plpgsql security definer;

-- =============================
-- 4. TRIGGER - Execute on new auth user
-- =============================
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- =============================
-- 5. EXAM STRUCTURE (Same structure)
-- =============================
create table if not exists exam_structures (
  exam_structure_id integer generated by default as identity primary key,
  name varchar(100) not null,
  description text,
  total_parts integer not null,
  duration_minutes integer,
  is_active boolean default true,
  created_at timestamptz default now()
);

create table if not exists parts (
  part_id integer generated by default as identity primary key,
  exam_structure_id integer references exam_structures on delete cascade,
  part_type_id integer references part_types,
  part_number integer not null,
  title varchar(200),
  instructions text,
  time_limit integer,
  min_words integer,
  max_words integer
);

-- =============================
-- 6. PRACTICE SESSIONS
-- =============================
create table if not exists practice_sessions (
  session_id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  mode_id integer references practice_modes,
  is_random boolean default true,
  status varchar(20) default 'active',
  started_at timestamptz default now(),
  ended_at timestamptz
);

-- =============================
-- 7. TOPICS & CONTENT
-- =============================
create table if not exists topics (
  topic_id bigint generated by default as identity primary key,
  part_id integer references parts on delete cascade,
  difficulty_level_id integer references levels,
  topic_name varchar(255) not null,
  content text,
  context text,
  purpose text,
  recipient_role varchar(100),
  min_words integer,
  max_words integer,
  is_active boolean default true,
  created_at timestamptz default now()
);

-- =============================
-- 8. USER SUBMISSIONS
-- =============================
create table if not exists user_submissions (
  submission_id bigint generated by default as identity primary key,
  session_id bigint references practice_sessions on delete cascade,
  topic_id bigint references topics,
  part_id integer references parts,
  content text not null,
  word_count integer,
  submitted_at timestamptz default now()
);

-- =============================
-- 9. AI EVALUATION
-- =============================
create table if not exists ai_evaluations (
  evaluation_id bigint generated by default as identity primary key,
  submission_id bigint unique references user_submissions on delete cascade,
  total_score float,
  estimated_level_id integer references levels,
  overall_feedback text,
  strengths text,
  weaknesses text,
  suggestions text,
  evaluated_at timestamptz default now()
);

-- =============================
-- 10. PASSWORD RESET TOKENS
-- =============================
create table if not exists password_reset_tokens (
  token_id bigint generated by default as identity primary key,
  user_id uuid references profiles(id) on delete cascade,
  token varchar(100) unique not null,
  expires_at timestamptz not null,
  used boolean default false,
  created_at timestamptz default now()
);

