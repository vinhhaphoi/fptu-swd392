-- 12. ROW LEVEL SECURITY
-- =============================
alter table profiles enable row level security;
alter table practice_sessions enable row level security;
alter table user_submissions enable row level security;
alter table password_reset_tokens enable row level security;

-- =============================
-- 13. RLS POLICIES
-- =============================

-- Profile: user can access own profile
create policy "Profile self access"
on profiles
for all
using (id = auth.uid());

-- Sessions: user manages own sessions
create policy "Session self access"
on practice_sessions
for all
using (user_id = auth.uid());

-- Submissions: user manages own submissions
create policy "Submission self access"
on user_submissions
for all
using (
  session_id in (
    select ps.session_id
    from practice_sessions ps
    where ps.user_id = auth.uid()
  )
);

-- Password reset tokens: user can access own tokens
create policy "Password reset token self access"
on password_reset_tokens
for all
using (user_id = auth.uid());

