-- =============================
-- 0. EXTENSIONS
-- =============================
create extension if not exists "uuid-ossp";

-- =============================
-- 1. LOOKUP TABLES (Same as before)
-- =============================
create table if not exists levels (
  level_id integer generated by default as identity primary key,
  level_code varchar(5) unique not null,
  description varchar(100)
);

create table if not exists part_types (
  part_type_id integer generated by default as identity primary key,
  code varchar(20) unique not null,
  description varchar(100)
);

create table if not exists practice_modes (
  mode_id integer generated by default as identity primary key,
  code varchar(30) unique not null,
  description varchar(100)
);

create table if not exists hint_types (
  hint_type_id integer generated by default as identity primary key,
  code varchar(30) unique not null,
  description varchar(100)
);

create table if not exists prompt_purposes (
  purpose_id integer generated by default as identity primary key,
  code varchar(30) unique not null,
  description varchar(100)
